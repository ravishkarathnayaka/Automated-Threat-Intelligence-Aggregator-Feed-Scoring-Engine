"""Snort 3 modern IPS detection and prevention ruleset exporter."""

from typing import Any, Dict, Iterable, Union
from cti_core.models.indicator import IndicatorModel, IndicatorRead


class Snort3Exporter:
    """Generates modern Snort 3 syntax detection and blocking rules."""

    @classmethod
    def export_rules(
        cls,
        indicators: Iterable[Union[IndicatorModel, IndicatorRead, Dict[str, Any]]],
        action: str = "reject",
        base_sid: int = 4000000,
        min_score: float = 75.0,
    ) -> str:
        """Generates modern Snort 3 rule file."""
        lines = [
            "# -------------------------------------------------------------",
            "# Snort 3 IPS Ruleset - Generated by SENTINEL-CTI Engine",
            "# -------------------------------------------------------------",
        ]
        sid = base_sid

        for item in indicators:
            if isinstance(item, dict):
                norm_val = item.get("normalized_value") or item.get("value", "")
                ioc_type = item.get("type", "").lower()
                score = float(item.get("confidence_score", 0.0))
                is_whitelisted = item.get("is_whitelisted", False)
            elif isinstance(item, IndicatorRead):
                norm_val = item.normalized_value
                ioc_type = item.type.value.lower()
                score = float(item.confidence_score)
                is_whitelisted = bool(item.is_whitelisted)
            else:
                norm_val = str(item.normalized_value)
                ioc_type = str(item.type).lower()
                score = float(item.confidence_score)
                is_whitelisted = bool(item.is_whitelisted)

            if is_whitelisted or score < min_score or not norm_val:
                continue

            sid += 1
            if ioc_type in ("ipv4", "ipv6"):
                lines.append(
                    f'{action} ip $HOME_NET any -> {norm_val} any '
                    f'(msg:"SENTINEL-CTI Snort3 Outbound C2 [{norm_val}]"; '
                    f'sid:{sid}; rev:1; classtype:trojan-activity; '
                    f'metadata:engine sentinel_cti, confidence {score:.1f};)'
                )
            elif ioc_type == "domain":
                lines.append(
                    f'{action} http $HOME_NET any -> any any '
                    f'(msg:"SENTINEL-CTI Snort3 Malicious Host [{norm_val}]"; '
                    f'http_header:field host; content:"{norm_val}"; '
                    f'sid:{sid}; rev:1; classtype:trojan-activity; '
                    f'metadata:engine sentinel_cti, confidence {score:.1f};)'
                )

        return "\n".join(lines)
