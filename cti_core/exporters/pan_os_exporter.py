"""Palo Alto Networks (PAN-OS) External Dynamic List (EDL) & Custom Category XML exporter."""

from datetime import datetime, timezone
from typing import Any, Dict, Iterable, List, Union
from xml.sax.saxutils import escape

from cti_core.models.indicator import IndicatorModel, IndicatorRead


class PanOSExporter:
    """Exports indicators into Palo Alto Networks PAN-OS compatible EDL and XML Category formats."""

    @classmethod
    def export_edl_xml(
        cls,
        indicators: Iterable[Union[IndicatorModel, IndicatorRead, Dict[str, Any]]],
        category_name: str = "SENTINEL-CTI-MALICIOUS",
        min_score: float = 70.0,
    ) -> str:
        """Export high-confidence indicators into PAN-OS Custom URL / IP Category XML."""
        now_utc = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
        entries: List[str] = []

        seen_values = set()

        for item in indicators:
            if isinstance(item, dict):
                norm_val = item.get("normalized_value") or item.get("value", "")
                ioc_type = item.get("type", "").lower()
                score = float(item.get("confidence_score", 0.0))
                is_whitelisted = item.get("is_whitelisted", False)
            elif isinstance(item, IndicatorRead):
                norm_val = item.normalized_value
                ioc_type = item.type.value.lower()
                score = float(item.confidence_score)
                is_whitelisted = bool(item.is_whitelisted)
            else:  # IndicatorModel
                norm_val = str(item.normalized_value)
                ioc_type = str(item.type).lower()
                score = float(item.confidence_score)
                is_whitelisted = bool(item.is_whitelisted)

            if is_whitelisted or score < min_score:
                continue

            # PAN-OS EDL categories support IPs, domains, and URLs
            if ioc_type not in ("ipv4", "ipv6", "domain", "url"):
                continue

            if norm_val in seen_values:
                continue
            seen_values.add(norm_val)

            escaped_val = escape(norm_val)
            entries.append(f"      <member>{escaped_val}</member>")

        xml_lines = [
            '<?xml version="1.0" encoding="UTF-8"?>',
            f"<!-- Generated by SENTINEL CTI Engine: {now_utc} -->",
            f"<!-- Minimum Confidence Threshold: {min_score} | Total Members: {len(entries)} -->",
            '<response status="success">',
            "  <result>",
            f'    <custom-url-category name="{escape(category_name)}">',
            "      <type>URL List</type>",
            "      <list>",
        ]
        xml_lines.extend(entries)
        xml_lines.extend([
            "      </list>",
            "    </custom-url-category>",
            "  </result>",
            "</response>",
        ])

        return "\n".join(xml_lines) + "\n"
