"""YARA rule generator for malicious file hashes."""

from datetime import datetime, timezone
import re
from typing import Any, Dict, Iterable, List, Union

from cti_core.models.indicator import IndicatorModel, IndicatorRead


class YARAExporter:
    """Generates standard YARA rules from malicious cryptographic hashes."""

    @classmethod
    def export_rules(
        cls,
        indicators: Iterable[Union[IndicatorModel, IndicatorRead, Dict[str, Any]]],
        rule_name: str = "Sentinel_CTI_Detected_Malware_Hashes",
        min_score: float = 75.0,
    ) -> str:
        """Export high-confidence hashes into a compiled YARA rule."""
        hashes: List[Dict[str, str]] = []
        seen = set()

        for item in indicators:
            if isinstance(item, dict):
                norm_val = (item.get("normalized_value") or item.get("value", "")).strip().lower()
                ioc_type = item.get("type", "").lower()
                score = float(item.get("confidence_score", 0.0))
                is_whitelisted = item.get("is_whitelisted", False)
            elif isinstance(item, IndicatorRead):
                norm_val = item.normalized_value.strip().lower()
                ioc_type = item.type.value.lower()
                score = float(item.confidence_score)
                is_whitelisted = bool(item.is_whitelisted)
            else:  # IndicatorModel
                norm_val = str(item.normalized_value).strip().lower()
                ioc_type = str(item.type).lower()
                score = float(item.confidence_score)
                is_whitelisted = bool(item.is_whitelisted)

            if is_whitelisted or score < min_score:
                continue

            if ioc_type in {"sha256", "sha1", "md5"}:
                if norm_val not in seen:
                    seen.add(norm_val)
                    hashes.append({"type": ioc_type, "value": norm_val, "score": str(score)})

        safe_rule_name = re.sub(r"[^a-zA-Z0-9_]", "_", rule_name)
        now_str = datetime.now(timezone.utc).strftime("%Y-%m-%d")

        if not hashes:
            return (
                f"/* No active hashes matching min_score={min_score} */\n"
                f'import "hash"\n\n'
                f"rule {safe_rule_name} {{\n"
                f"    meta:\n"
                f'        description = "Sentinel CTI Empty Indicator Set"\n'
                f'        date = "{now_str}"\n'
                f"    condition:\n"
                f"        false\n"
                f"}}\n"
            )

        lines = [
            f'/* Generated by Sentinel CTI Engine at {now_str} */',
            'import "hash"',
            "",
            f"rule {safe_rule_name} {{",
            "    meta:",
            f'        description = "Automated high-confidence malicious hash detection"',
            f'        author = "Sentinel CTI Aggregator"',
            f'        date = "{now_str}"',
            f'        hash_count = {len(hashes)}',
            "    condition:",
        ]

        conditions = []
        for h in hashes:
            htype = h["type"]
            val = h["value"]
            if htype == "sha256":
                conditions.append(f'        hash.sha256(0, filesize) == "{val}"')
            elif htype == "sha1":
                conditions.append(f'        hash.sha1(0, filesize) == "{val}"')
            elif htype == "md5":
                conditions.append(f'        hash.md5(0, filesize) == "{val}"')

        lines.append(" or\n".join(conditions))
        lines.append("}\n")

        return "\n".join(lines)
