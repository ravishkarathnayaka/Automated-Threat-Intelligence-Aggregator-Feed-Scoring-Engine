"""Zeek (Bro) Notice policy scripting language exporter."""

from typing import Any, Dict, Iterable, List, Union
from cti_core.models.indicator import IndicatorModel, IndicatorRead


class ZeekNoticeExporter:
    """Generates Zeek policy scripts for immediate connection alerting."""

    @classmethod
    def export_script(
        cls,
        indicators: Iterable[Union[IndicatorModel, IndicatorRead, Dict[str, Any]]],
        notice_name: str = "SentinelCTI::MaliciousConnection",
        min_score: float = 80.0,
    ) -> str:
        """Generates Zeek notice policy script."""
        ips: List[str] = []

        for item in indicators:
            if isinstance(item, dict):
                norm_val = item.get("normalized_value") or item.get("value", "")
                ioc_type = item.get("type", "").lower()
                score = float(item.get("confidence_score", 0.0))
                is_whitelisted = item.get("is_whitelisted", False)
            elif isinstance(item, IndicatorRead):
                norm_val = item.normalized_value
                ioc_type = item.type.value.lower()
                score = float(item.confidence_score)
                is_whitelisted = bool(item.is_whitelisted)
            else:
                norm_val = str(item.normalized_value)
                ioc_type = str(item.type).lower()
                score = float(item.confidence_score)
                is_whitelisted = bool(item.is_whitelisted)

            if is_whitelisted or score < min_score or not norm_val:
                continue

            if ioc_type in ("ipv4", "ipv6") and norm_val not in ips:
                ips.append(norm_val)

        ip_set_items = ", ".join(f"{ip}" for ip in ips) if ips else "127.0.0.1"

        return f"""# Zeek Notice Policy Script - Generated by SENTINEL CTI
@load base/frameworks/notice

module SentinelCTI;

export {{
    redef enum Notice::Type += {{
        MaliciousConnection
    }};

    const blocklist_ips: set[addr] = {{
        {ip_set_items}
    }} &redef;
}}

event connection_established(c: connection)
{{
    if ( c$id$resp_h in blocklist_ips )
    {{
        NOTICE([$note=MaliciousConnection,
                $msg=fmt("Outbound connection to CTI confirmed malicious IP: %s", c$id$resp_h),
                $conn=c,
                $identifier=cat(c$id$orig_h, c$id$resp_h)]);
    }}
}}
"""
