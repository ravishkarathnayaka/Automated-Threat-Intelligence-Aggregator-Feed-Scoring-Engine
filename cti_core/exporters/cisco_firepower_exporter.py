"""Cisco Firepower Management Center (FMC) Network Object exporter."""

import json
from typing import Any, Dict, Iterable, List, Union
from cti_core.models.indicator import IndicatorModel, IndicatorRead


class CiscoFirepowerExporter:
    """Exports threat indicators into Cisco Firepower Management Center (FMC) Network Objects JSON."""

    @classmethod
    def export_fmc_objects(
        cls,
        indicators: Iterable[Union[IndicatorModel, IndicatorRead, Dict[str, Any]]],
        min_score: float = 75.0,
    ) -> str:
        """Generates Cisco FMC REST API payload for bulk Network Host/Object creation."""
        objects: List[Dict[str, Any]] = []

        for item in indicators:
            if isinstance(item, dict):
                norm_val = item.get("normalized_value") or item.get("value", "")
                ioc_type = item.get("type", "").lower()
                score = float(item.get("confidence_score", 0.0))
                is_whitelisted = item.get("is_whitelisted", False)
            elif isinstance(item, IndicatorRead):
                norm_val = item.normalized_value
                ioc_type = item.type.value.lower()
                score = float(item.confidence_score)
                is_whitelisted = bool(item.is_whitelisted)
            else:
                norm_val = str(item.normalized_value)
                ioc_type = str(item.type).lower()
                score = float(item.confidence_score)
                is_whitelisted = bool(item.is_whitelisted)

            if is_whitelisted or score < min_score or not norm_val:
                continue

            if ioc_type in ("ipv4", "ipv6"):
                obj_name = f"SENTINEL_HOST_{norm_val.replace('.', '_').replace(':', '_')}"
                objects.append({
                    "name": obj_name,
                    "type": "Host",
                    "value": norm_val,
                    "description": f"Auto-generated by SENTINEL-CTI (Score: {score})",
                    "overridable": False,
                })
            elif ioc_type == "domain":
                obj_name = f"SENTINEL_DNS_{norm_val.replace('.', '_')}"
                objects.append({
                    "name": obj_name,
                    "type": "FQDN",
                    "value": norm_val,
                    "description": f"Auto-generated by SENTINEL-CTI (Score: {score})",
                    "overridable": False,
                })

        payload = {
            "version": "1.0",
            "generator": "SENTINEL-CTI-Engine",
            "networkObjects": objects,
            "totalCount": len(objects),
        }
        return json.dumps(payload, indent=2)
