"""Juniper Junos SRX firewall address book and security policy configuration exporter."""

from typing import Any, Dict, Iterable, List, Union
from cti_core.models.indicator import IndicatorModel, IndicatorRead


class JuniperSRXExporter:
    """Exports threat indicators into Juniper Junos hierarchical 'set' configuration commands."""

    @classmethod
    def export_set_commands(
        cls,
        indicators: Iterable[Union[IndicatorModel, IndicatorRead, Dict[str, Any]]],
        zone_name: str = "untrust",
        address_set_name: str = "SENTINEL_BLOCK_SET",
        min_score: float = 75.0,
    ) -> str:
        """Generates Junos CLI set commands for address-book entries and address-set."""
        commands: List[str] = [
            f"# Junos SRX Threat Drop Configuration - Generated by SENTINEL-CTI",
            f"set security zones security-zone {zone_name} address-book address-set {address_set_name} description 'Automated Threat Intelligence Blocklist'",
        ]

        for item in indicators:
            if isinstance(item, dict):
                norm_val = item.get("normalized_value") or item.get("value", "")
                ioc_type = item.get("type", "").lower()
                score = float(item.get("confidence_score", 0.0))
                is_whitelisted = item.get("is_whitelisted", False)
            elif isinstance(item, IndicatorRead):
                norm_val = item.normalized_value
                ioc_type = item.type.value.lower()
                score = float(item.confidence_score)
                is_whitelisted = bool(item.is_whitelisted)
            else:
                norm_val = str(item.normalized_value)
                ioc_type = str(item.type).lower()
                score = float(item.confidence_score)
                is_whitelisted = bool(item.is_whitelisted)

            if is_whitelisted or score < min_score or not norm_val:
                continue

            if ioc_type in ("ipv4", "ipv6"):
                addr_name = f"THREAT_{norm_val.replace('.', '_').replace(':', '_')}"
                cidr = f"{norm_val}/32" if ioc_type == "ipv4" and "/" not in norm_val else norm_val
                commands.append(f"set security zones security-zone {zone_name} address-book address {addr_name} {cidr}")
                commands.append(f"set security zones security-zone {zone_name} address-book address-set {address_set_name} address {addr_name}")
            elif ioc_type == "domain":
                addr_name = f"DNS_{norm_val.replace('.', '_')}"
                commands.append(f"set security zones security-zone {zone_name} address-book address {addr_name} dns-name {norm_val}")
                commands.append(f"set security zones security-zone {zone_name} address-book address-set {address_set_name} address {addr_name}")

        return "\n".join(commands)
